/**
 * Regenerate packages/common/src/google/gog/snapshot.ts: the commands, flags
 * and positionals the Gmail catalog uses (packages/common/src/google/gog/
 * commands.ts), each with the type one gog release declares for it, and its
 * exit codes. Offline: it reads a saved `gog schema --json`, or runs the
 * given binary's `schema --json` the way the transport runs gog: its
 * allow-listed environment (environment.ts) over a fresh empty home, and the
 * runner's process group and cap. That reaches no account and writes
 * nothing.
 *
 *   bun scripts/gog-schema-snapshot.ts --schema <schema.json>
 *   bun scripts/gog-schema-snapshot.ts --gog <path to a pinned gog binary>
 *
 * Part of a gog upgrade (plan §8): regenerate, run the live shape check and
 * the disposable-account write proof, then add the version to the pins.
 * Refuses when the release lacks a command or flag the catalog uses, when the
 * catalog names a forbidden flag, or when the exit codes differ from the
 * mapping in errors.ts, which must change first.
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { GOG_COMMANDS, GOG_FORBIDDEN_FLAGS, GOG_ROOT_FLAGS, type GogCommand, type GogSchemaSnapshot } from "../packages/common/src/google/gog/commands.ts";
import { gogEnvironment } from "../packages/common/src/google/gog/environment.ts";
import { GOG_EXIT_CODES } from "../packages/common/src/google/gog/errors.ts";
import { GOG_SCHEMA_STDOUT_CAP, runGogProcess } from "../packages/common/src/google/gog/runner.ts";

export const SNAPSHOT_FILE = resolve(import.meta.dir, "../packages/common/src/google/gog/snapshot.ts");

type Node = { name?: string; flags?: { name: string; type: string }[]; positionals?: { name: string; type: string }[]; subcommands?: Node[] };

/** The snapshot of one parsed `gog schema --json`. Throws naming what is missing. */
export function snapshotFromSchema(schema: { schema_version?: unknown; build?: unknown; command?: Node; automation?: { exit_codes?: Record<string, number> } }): GogSchemaSnapshot {
  if (typeof schema.build !== "string" || typeof schema.schema_version !== "number" || !schema.command) throw new Error("not a gog schema --json document");
  const codes = schema.automation?.exit_codes ?? {};
  const expected: Record<string, number> = GOG_EXIT_CODES;
  const sameCodes = Object.keys(codes).length === Object.keys(expected).length && Object.entries(expected).every(([name, code]) => codes[name] === code);
  if (!sameCodes) throw new Error(`gog's exit codes differ from errors.ts (${JSON.stringify(codes)}); update the mapping first`);
  const types = (list: Node["flags"], names: readonly string[], where: string) => Object.fromEntries(names.map(name => {
    const found = list?.find(entry => entry.name === name);
    if (!found) throw new Error(`${where} has no ${name}`);
    return [name, found.type];
  }));
  const commands = {} as Record<GogCommand, GogSchemaSnapshot["commands"][GogCommand]>;
  for (const [command, spec] of Object.entries(GOG_COMMANDS) as [GogCommand, typeof GOG_COMMANDS[GogCommand]][]) {
    for (const flag of spec.flags) if (GOG_FORBIDDEN_FLAGS.includes(flag)) throw new Error(`${command} names the forbidden flag --${flag}`);
    let node: Node | undefined = schema.command;
    for (const name of spec.path) node = node?.subcommands?.find(entry => entry.name === name);
    if (!node) throw new Error(`gog has no command ${spec.path.join(" ")}`);
    commands[command] = {
      path: spec.path,
      flags: types(node.flags, spec.flags, `gog ${spec.path.join(" ")}`),
      positionals: types(node.positionals, spec.positionals, `gog ${spec.path.join(" ")} (positionals)`),
    };
  }
  return {
    gog: schema.build,
    schema_version: schema.schema_version,
    exit_codes: { ...GOG_EXIT_CODES },
    root_flags: types(schema.command.flags, GOG_ROOT_FLAGS, "gog"),
    commands,
  };
}

export function renderSnapshot(snapshot: GogSchemaSnapshot): string {
  return `/**
 * Generated by scripts/gog-schema-snapshot.ts from \`gog schema --json\` of
 * ${snapshot.gog}. Do not edit: change commands.ts and regenerate.
 *
 * The commands, flags and positionals the catalog uses, with gog's types,
 * and gog's exit codes. Every argv builder uses only these flags
 * (tests/google-gog-argv.test.ts), and the pin checks a binary's own schema
 * against them at first use.
 */
import type { GogSchemaSnapshot } from "./commands.js";

export const GOG_SCHEMA_SNAPSHOT: GogSchemaSnapshot = ${JSON.stringify(snapshot, null, 2)
  .replace(/"([A-Za-z_][A-Za-z0-9_]*)":/g, "$1:")
  .replace(/\[\s+([^[\]{}]*?)\s+\]/g, (_, items: string) => `[${items.split(/,\s+/).join(", ")}]`)};
`;
}

/** `gog schema --json` of one binary, run with the transport's environment over a fresh empty home. */
export async function schemaFromBinary(gog: string): Promise<unknown> {
  const home = mkdtempSync(join(tmpdir(), "gog-schema-"));
  try {
    // `schema` opens no keyring; the allow-list needs a password all the same.
    const environment = gogEnvironment({ home, keyringPassword: "schema-snapshot-opens-no-keyring" });
    if (!environment.ok) throw new Error(`no gog environment: ${environment.reason}`);
    const run = await runGogProcess(gog, ["schema", "--json"], { env: environment.environment, stdin: null, timeoutMs: 60_000, stdoutCap: GOG_SCHEMA_STDOUT_CAP });
    if (run.end.kind !== "exit" || run.end.exitCode !== 0 || !run.stdout) {
      throw new Error(`gog schema --json ended ${run.end.kind === "exit" ? `with exit ${run.end.exitCode}` : `by ${run.end.kind}`}`);
    }
    return JSON.parse(new TextDecoder().decode(run.stdout));
  } finally {
    rmSync(home, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const [flag, value] = process.argv.slice(2);
  if (!value || (flag !== "--schema" && flag !== "--gog")) {
    console.error("usage: bun scripts/gog-schema-snapshot.ts --schema <schema.json> | --gog <gog binary>");
    process.exit(2);
  }
  const schema = flag === "--schema" ? JSON.parse(readFileSync(value, "utf8")) : await schemaFromBinary(resolve(value));
  const snapshot = snapshotFromSchema(schema);
  writeFileSync(SNAPSHOT_FILE, renderSnapshot(snapshot));
  console.log(`wrote ${SNAPSHOT_FILE} from ${snapshot.gog}`);
}
