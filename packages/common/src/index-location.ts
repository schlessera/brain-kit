/**
 * Where a brain keeps its disposable search index.
 *
 * Internal to brain-kit: reached through
 * `@schlessera/brain-common/internal/index-location`, with no compatibility
 * promise for the module itself. The location it names is part of the
 * integration contract (docs/integration-contract/frontmatter.md, "brain.db").
 *
 * The SQLite database and its sidecars live together in one directory below
 * the brain root, never as loose files in the root. A directory can be
 * retained and replaced as a whole inside a worker's mount namespace; a loose
 * file mask detaches when a peer unlinks or renames the path it covers
 * (docs/decisions/governed-writable-workers.md, "The index directory").
 *
 * Markdown stays the source of truth: everything in this directory is
 * regenerated by `brain index --force`.
 */

import { join } from "node:path";

/** Repo-relative directory holding the index database and its SQLite sidecars. */
export const INDEX_DIR = ".brain-index";

/** The index database's file name inside {@link INDEX_DIR}. */
export const INDEX_DB = "brain.db";

/** The database and every sidecar SQLite may create beside it, database first. */
export const INDEX_FAMILY = ["brain.db", "brain.db-wal", "brain.db-shm", "brain.db-journal"] as const;

/** Repo-relative path of the index database. */
export const INDEX_DB_PATH = `${INDEX_DIR}/${INDEX_DB}`;

/** Absolute index database path for a brain root. */
export function indexDbPath(root: string): string {
  return join(root, INDEX_DIR, INDEX_DB);
}

/**
 * The root-level names releases before 0.44.0 kept the index under. Nothing
 * reads or writes them any more: a brain migrates by rebuilding its index in
 * {@link INDEX_DIR}, and these copies are removed rather than moved.
 */
export const LEGACY_INDEX_FAMILY = [
  ...INDEX_FAMILY,
  // `index --embeddings`' cross-process lock database, kept beside brain.db.
  "brain.db.embedding-lock.db", "brain.db.embedding-lock.db-journal", "brain.db.embedding-lock.db-wal", "brain.db.embedding-lock.db-shm",
] as const;
