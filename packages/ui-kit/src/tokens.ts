/**
 * A stylesheet that sets every token to its print value on `:root`, for a
 * document with no kit stylesheet at all: the share renderer's page, which
 * loads nothing and runs no script. The components read only `var(--bk-*)`,
 * so this is all they need to draw in print.
 */
export function printThemeCss(): string {
  const declarations = Object.entries(PRINT_TOKENS)
    .map(([name, value]) => `--bk-${name}:${value};`)
    .join("");
  return `:root{color-scheme:light;${declarations}}`;
}

/**
 * `var(--bk-<name>)` — how every colour reaches the DOM.
 *
 * Deliberately no fallback. The argument is typed, so the name is checked; the
 * VALUE comes from the stylesheet and nowhere else, which is what makes a theme
 * swap total rather than partial.
 */
export function token(name: TokenName): string {
  return `var(--bk-${name})`;
}

