import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { checkDiagram } from "../src/check.js";
const fixture = readFileSync(new URL("./fixtures/free-valid.diagram.yaml", import.meta.url), "utf8");
test("labels cannot be shrunk below the 9px floor to fit", () => {
 const source = fixture.replace("label: The raft", "label: The very long homecoming message from the raft");
 expect(checkDiagram(source).errors.some(f => f.code === "text_floor")).toBe(true);
});
test("approved dark cluster border and white print group are shared tokens", () => {
 const css = readFileSync(new URL("../../ui-kit/src/tokens.css", import.meta.url), "utf8");
 expect(css).toContain("--bk-diagram-cluster-border: light-dark(#847c6f, #6b6873)");
 expect(css.slice(css.indexOf("/* @print-theme:start */"))).toContain("--bk-diagram-cluster: #ffffff;");
});

import { generateSkin } from "../scripts/generate-skin.js";
import { DIAGRAM_PALETTE, DIAGRAM_TOKEN_CSS, DIAGRAM_TYPE, diagramNodePaint, diagramEdgePaint, contrastRatio, typeWidthBudget } from "../src/skin.js";
import { buildDiagramLayout } from "../src/layout.js";
import { parse } from "yaml";
test("the embedded block is regenerated byte-for-byte from canonical CSS", () => {
 expect(readFileSync(new URL("../src/skin.generated.ts", import.meta.url), "utf8")).toBe(generateSkin());
 const css = readFileSync(new URL("../../ui-kit/src/tokens.css", import.meta.url), "utf8");
 expect(generateSkin(css.replace("#6b6873", "#6b6874"))).not.toBe(generateSkin(css));
 expect(DIAGRAM_TOKEN_CSS).toContain("@media print{.bk-diagram.bk-diagram,.bk-diagram.bk-diagram[data-theme],[data-theme] .bk-diagram");
});
test("all paint roles are token references, with approved focal sublabel and connector cues", () => {
 for (const role of ["default", "focal", "store", "input", "external", "optional", "boundary"]) {
  const paint = diagramNodePaint(role); for (const key of ["fill", "stroke", "text", "sub"] as const) expect(paint[key]).toMatch(/^var\(--bk-/);
 }
 expect(diagramNodePaint("focal").sub).toBe("var(--bk-diagram-text)");
 expect(diagramEdgePaint("async")).toMatchObject({ dash: "1.5 3.5", linecap: "round", head: "open" });
 expect(diagramEdgePaint("return")).toMatchObject({ dash: "6 4", head: "open" });
 expect(diagramEdgePaint("link").head).toBe("hollow");
 expect(contrastRatio(DIAGRAM_PALETTE.dark!["diagram-text"]!, DIAGRAM_PALETTE.dark!["diagram-focal-tint"]!)).toBeGreaterThan(9.5);
});
test("check refuses an actual below-bar paint pair in each theme", () => {
 for (const theme of ["light", "dark", "print"] as const) {
  const previous = DIAGRAM_PALETTE[theme]["diagram-text"]!;
  try { DIAGRAM_PALETTE[theme]["diagram-text"] = DIAGRAM_PALETTE[theme]["diagram-node"]!;
   expect(checkDiagram(fixture).errors.some(f => f.code === "contrast" && f.message.startsWith(theme))).toBe(true);
  } finally { DIAGRAM_PALETTE[theme]["diagram-text"] = previous; }
 }
 expect(checkDiagram(fixture).valid).toBe(true);
});
test("type budgets distinguish wide characters and reject below-floor metrics", () => {
 expect(typeWidthBudget("WWW", "name")).toBeGreaterThan(typeWidthBudget("iii", "name"));
 expect(typeWidthBudget("旅", "name")).toBeGreaterThan(typeWidthBudget("i", "name"));
 expect(() => typeWidthBudget("raft", "name", 8.9)).toThrow("9px");
 expect(Object.values(DIAGRAM_TYPE).every(style => style.size >= 9)).toBe(true);
});
const narrow = () => ({ ...parse(fixture), groups: [], layouts: { narrow: { width: 320, height: 256, nodes: [{ id: "raft", at: [40, 40], size: [148, 64] }, { id: "ithaca", at: [40, 160], size: [148, 64] }] } } });
test("authored narrow placement shares semantic IDs and produces the exact frame", () => {
 const spec = narrow(); expect(checkDiagram(JSON.stringify(spec)).errors).toEqual([]);
 const tree = buildDiagramLayout(spec, "narrow"); expect(tree.viewBox).toEqual({ x: 0, y: 0, width: 320, height: 256 });
 expect(tree.elements.filter(e => e.kind === "node").map(e => e.id)).toEqual(["raft", "ithaca"]);
 expect(() => buildDiagramLayout(parse(fixture), "narrow")).toThrow("No authored narrow");
});
test("narrow layout refuses missing, duplicate, extra, out-of-bounds, non-grid, overlap and undersized text", () => {
 const mutations = [
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes.pop(),
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes.push(s.layouts.narrow.nodes[0]!),
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes[0]!.id = "extra",
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes[0]!.at[0] = 312,
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes[0]!.at[0] = 41,
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes[1]!.at = [40, 40],
  (s: ReturnType<typeof narrow>) => s.layouts.narrow.nodes[0]!.size[0] = 16,
 ];
 for (const mutate of mutations) { const spec = narrow(); mutate(spec); expect(checkDiagram(JSON.stringify(spec)).valid).toBe(false); }
});
test("no module source contains hand-authored color literals", () => {
 for (const file of new Bun.Glob("**/*.{ts,tsx,css}").scanSync({ cwd: new URL("../src", import.meta.url).pathname, absolute: true })) {
  if (file.endsWith("skin.generated.ts")) continue;
  // Computed RGB serialization from canonical tokens is not an authored color.
  const literals = readFileSync(file, "utf8").match(/#[\da-f]{3,8}\b|(?:rgb|hsl)a?\((?!\$\{)/ig) ?? [];
  expect({ file: file.split("/").at(-1), literals }).toEqual({ file: file.split("/").at(-1), literals: [] });
 }
});
import { fitDiagramText } from "../src/skin.js";
test("generated role tags occupy a real line and shared fitting never clips", () => {
 const source = parse(fixture); source.nodes[0].size = [148, 28];
 expect(checkDiagram(JSON.stringify(source)).errors.some(f => f.code === "text_floor" && f.path.endsWith("size[1]"))).toBe(true);
 expect(() => fitDiagramText("The long homecoming relay", "name", 16)).toThrow("9px");
 const fitted = fitDiagramText("Homecoming relay", "name", 104);
 expect(fitted).toBeGreaterThanOrEqual(9);
 expect(typeWidthBudget("Homecoming relay", "name", fitted)).toBeLessThanOrEqual(104.000001);
});
test("a changed canonical focus alias stops generation", () => {
 const css = readFileSync(new URL("../../ui-kit/src/tokens.css", import.meta.url), "utf8");
 expect(() => generateSkin(css.replaceAll("--bk-focus-ring: var(--bk-color-ink);", "--bk-focus-ring: var(--bk-diagram-line);"))).toThrow("focus-ring alias changed");
});
test("group labels also retain the rendered text floor", () => {
 const spec = parse(fixture); spec.groups[0].label = "HOME ".repeat(100);
 expect(checkDiagram(JSON.stringify(spec)).errors.some(f => f.code === "text_floor" && f.path === "$.groups[0].label")).toBe(true);
});
